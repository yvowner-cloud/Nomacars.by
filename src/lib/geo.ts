export function stateInfo(code: string): { code: string; name: string; port: string; zone: Zone } {
  const c = String(code || "").toUpperCase();
  const s = S[c];
  return s ? { code: c, name: s[0], port: s[1], zone: s[2] } : { code: c || "—", name: c || "США", port: "Ньюарк", zone: "NJ" };
}

