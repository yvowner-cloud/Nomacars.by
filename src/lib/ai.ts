const POPULAR = ["Toyota", "Hyundai", "Kia", "Honda", "Mazda"];

export function aiReview(l: Lot) {
  if (l.review?.summary) {
    const why = l.review.why.length ? [...l.review.why] : [];
    if (l.monthKnown !== false) why.push(`Проходной возраст: льготная пошлина до ${graceUntil(l)}`);
    return { summary: l.review.summary, plain: l.review.plain || ZONE[l.zone].plain, why, risks: l.review.risks };
  }
  const z = ZONE[l.zone];
  const why = [
    l.level === "light" ? "Лёгкое повреждение, силовые элементы не затронуты" : "Повреждение среднее, но ремонт предсказуемый",
    POPULAR.includes(l.make) ? "Популярная модель: запчасти и сервис есть в РБ и РФ" : "Хорошая комплектация за свои деньги",
    `Проходной возраст: льготная пошлина до ${graceUntil(l)}`,
  ];
  if (l.miles < 25000) why.push("Небольшой пробег для своего года");
  if (l.fuel === "Гибрид") why.push("Гибрид: расход 6–7 л в городе");
  const risks = [...z.risks];
  if (l.fuel === "Электро") risks.push("Нужно проверить состояние батареи по отчёту");
  if (l.hp > 160) risks.push("Для РФ: мощность больше 160 л.с., утильсбор выше");
  const summary = `${l.make} ${l.model} ${l.trim} ${l.year} года, ${kmStr(l.miles)} пробега. Повреждение: ${l.damage.toLowerCase()}. По фото машина заводится и едет, подушки на месте. После ремонта за ${money(l.repair[0])}–${money(l.repair[1]).replace("$ ", "")} её можно эксплуатировать без ограничений.`;
  return { summary, plain: z.plain, why, risks };
}
